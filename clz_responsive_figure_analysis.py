"""Notebook-friendly figure helpers for clozapine-responsive cell characterization.

This module is designed for interactive use from an ipynb after running the
preprocessing / drug-response workflow.  It prints a conversation-style figure
plan and, when enough annotations are present, creates the core tables/plots for
answering two distinct questions:

1. What are clozapine-responsive cells? (UMAP, cell type enrichment, layer markers)
2. Why are they pharmacologically recruitable? (receptor/cAMP signatures,
   synapse/plasticity gene-set summaries)

Example
-------
>>> import clz_responsive_figure_analysis as clzfig
>>> result = clzfig.run_clz_responsive_figure_story(
...     adata,
...     cell_type_col="cell_type",
...     output_dir="outputs/clz_responsive_figures",
... )
"""

